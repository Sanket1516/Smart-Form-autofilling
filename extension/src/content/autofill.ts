export interface ApprovedValue {
  field_id: string;
  concept: string;
  value: string;
  confidence: number;
}

export async function processAutofill(approvedValues: ApprovedValue[], sessionId: string, token: string) {
  for (const item of approvedValues) {
    const el = findElementByFieldId(item.field_id);
    if (!el) {
      console.warn(`Could not find element for field ${item.field_id} to autofill.`);
      continue;
    }

    if (isElementVisibleAndEditable(el)) {
      fillElement(el, item.value);
      
      // Delay slightly for any framework re-renders before verifying
      setTimeout(() => verifyFill(el, item.value, item.field_id, sessionId, token), 500);
    } else {
      console.warn(`Element for field ${item.field_id} is not editable or visible.`);
    }
  }
}

function findElementByFieldId(fieldId: string): HTMLElement | null {
  // We can try to use standard data attributes or simply query by id/name based on what's available
  // During detection, we use a custom attribute or just rely on standard DOM queries.
  // The simplest is to query by id or name if they were captured, or we could have stamped a custom attribute.
  // Since we don't stamp attributes in detection to avoid DOM pollution, we search for inputs matching id/name.
  
  // Note: the fieldId generated by detector is either the actual id, name, or a generated string.
  let el = document.getElementById(fieldId) || document.querySelector(`[name="${fieldId}"]`);
  
  if (!el) {
    // Attempt fallback search for inputs that might match
    const inputs = document.querySelectorAll('input, select, textarea');
    for (const input of inputs) {
      const iEl = input as HTMLInputElement;
      if (iEl.id === fieldId || iEl.name === fieldId) {
        return iEl;
      }
    }
  }
  return el as HTMLElement;
}

function isElementVisibleAndEditable(el: HTMLElement): boolean {
  if (el instanceof HTMLInputElement || el instanceof HTMLTextAreaElement || el instanceof HTMLSelectElement) {
    if (el.disabled || (el as any).readOnly) return false;
  }
  const rect = el.getBoundingClientRect();
  if (rect.width === 0 || rect.height === 0) return false;
  const style = window.getComputedStyle(el);
  if (style.display === 'none' || style.visibility === 'hidden') return false;
  
  return true;
}

function fillElement(el: HTMLElement, value: string) {
  el.focus();
  
  if (el instanceof HTMLInputElement || el instanceof HTMLTextAreaElement) {
    // Set native value setter to bypass React's tracking
    const nativeInputValueSetter = Object.getOwnPropertyDescriptor(window.HTMLInputElement.prototype, 'value')?.set;
    const nativeTextAreaValueSetter = Object.getOwnPropertyDescriptor(window.HTMLTextAreaElement.prototype, 'value')?.set;
    
    if (el instanceof HTMLInputElement && nativeInputValueSetter) {
      nativeInputValueSetter.call(el, value);
    } else if (el instanceof HTMLTextAreaElement && nativeTextAreaValueSetter) {
      nativeTextAreaValueSetter.call(el, value);
    } else {
      el.value = value;
    }
  } else if (el instanceof HTMLSelectElement) {
    el.value = value;
  }
  
  // Dispatch events for React/Angular/Vue
  el.dispatchEvent(new Event('input', { bubbles: true }));
  el.dispatchEvent(new Event('change', { bubbles: true }));
  el.blur();
}

function verifyFill(el: HTMLElement, expectedValue: string, fieldId: string, sessionId: string, token: string) {
  let actualValue = '';
  if (el instanceof HTMLInputElement || el instanceof HTMLTextAreaElement || el instanceof HTMLSelectElement) {
    actualValue = el.value;
  }
  
  const match = actualValue.trim().toLowerCase() === expectedValue.trim().toLowerCase();
  
  // Send to background for verification
  chrome.runtime.sendMessage({
    type: 'VERIFY_FIELD',
    payload: {
      sessionId,
      fieldId,
      filledValue: expectedValue,
      actualValue,
      match,
      token
    }
  });
}
